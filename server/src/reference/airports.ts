/**
 * Major international cargo airports: IATA code → ISO country, plus the city / airport names that
 * identify them unambiguously on an air waybill ("FRANKFURT/MAIN (FRA)", "Leipzig/Halle Airport").
 *
 * Used only to derive the COUNTRY of a departure airport (country of export fallback). CBP Schedule K
 * has no airports, and the CBP Form 7501 instructions (Block 19, rev. 02/26) say to leave the foreign
 * port of lading blank for non-vessel shipments, so no lading-port code is ever taken from here.
 *
 * Every code/country pair was checked on 2026-10-10 against OurAirports
 * (https://davidmegginson.github.io/ourairports-data/airports.csv, public domain): exactly one
 * non-closed airport carries the code, in the listed country. BSL was left out (EuroAirport
 * Basel-Mulhouse-Freiburg is in France although it serves Basel).
 *
 * Names are normalized (normalizeKey) and matched as whole words. City names that are also
 * notable places elsewhere (London ON, Manchester NH, Vienna VA, Paris TX, Dublin OH, Melbourne FL,
 * Lima OH, Cairo IL, Athens GA, Rome GA, Milan TN, Panama City FL, San Jose CA, Vancouver WA,
 * Hyderabad PK, Guadalajara ES, Barcelona VE, Santo Domingo EC…) are deliberately absent; their IATA
 * codes still resolve.
 */
export interface CargoAirport {
  iata: string;
  /** ISO 3166-1 alpha-2 */
  country: string;
  /** Normalized names that identify this airport (city or airport name). */
  names: string[];
}

